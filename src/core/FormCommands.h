#ifndef QTV8READER_FORMCOMMANDS_H
#define QTV8READER_FORMCOMMANDS_H

#include <QString>

namespace v8reader {

// В бинарной форме кнопка ссылается на команду не именем, а парой
// «номер, GUID»: {0, GUID} — стандартная команда платформы (Создать,
// Записать, Помощь), {0, GUID} с GUID общей команды конфигурации,
// {идентификатор, GUID коллекции команд формы} — команда самой формы,
// {идентификатор элемента, GUID} — стандартная команда элемента (таблицы,
// поля форматированного документа).
//
// GUID платформенных стандартных команд постоянны, поэтому ниже — таблицы
// «GUID -> имя», собранные сверкой с Form.xml по корпусу форм БП (294 кнопки,
// 26 форм). Имя уходит в модель как «Form.StandardCommand.<имя>» или
// «Form.Item.<элемент>.StandardCommand.<имя>»; заголовок кнопки рендерер
// берёт по этому имени (как и платформа — в Form.xml заголовка у таких
// кнопок нет).

// Имя стандартной команды формы по GUID или пустая строка.
QString formStandardCommandName(const QString &guid);

// Имя стандартной команды элемента (таблицы, поля форматированного
// документа, результата отчёта) по GUID или пустая строка.
QString itemStandardCommandName(const QString &guid);

} // namespace v8reader

#endif // QTV8READER_FORMCOMMANDS_H
